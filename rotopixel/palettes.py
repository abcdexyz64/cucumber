def get_palette(name: str) -> np.ndarray | None:
    if name == "Stable Posterize":
        return None
    colors = PALETTES.get(name)
    if colors is None:
        return None
    return np.asarray(colors, dtype=np.uint8)


def palette_names() -> list[str]:
    return ["Stable Posterize", *PALETTES.keys()]

